const { app } = require('electron');
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const profile = path.resolve(__dirname, '../../offline-preview/profile');
fs.mkdirSync(profile,{recursive:true});
app.setPath('userData',profile); app.disableHardwareAcceleration();
fs.writeFileSync(path.join(profile,'settings.json'),JSON.stringify({stats:false,autoRunes:false,autoItemSet:false,autoPopup:false,launchAtLogin:false,keyboardShortcut:''}));
fs.writeFileSync(path.join(profile,'choices.json'),'{}');
fs.writeFileSync(path.join(profile,'pick-pools.json'),'{}');
require('../src/lcu').findCredentials = async () => null;
process.argv.push('--background');
let win;
app.on('browser-window-created',(_e,w)=>{win=w;win.setPosition(-30000,-30000);win.show=win.showInactive.bind(win);win.focus=()=>{};});
require('../src/main');
const waitFor=async(fn,message)=>{const end=Date.now()+12000;while(Date.now()<end){if(await fn())return;await new Promise(r=>setTimeout(r,100));}throw Error(message);};
app.whenReady().then(async()=>{
  await waitFor(()=>win&&!win.webContents.isLoading(),'Renderer not ready');
  const evaluate=js=>win.webContents.executeJavaScript(js);
  await waitFor(()=>evaluate("document.body.innerText.includes('Uruchom klienta')"),'Offline state not shown');
  await evaluate("document.getElementById('draft-lab').click()");
  await waitFor(()=>evaluate("labView?.build?.alias === 'Leona'"),'Offline preview not calculated');
  await evaluate("document.querySelector('[data-pool-edit]').click()");
  await waitFor(()=>evaluate("document.querySelector('#pick-pool-dialog')?.open && !document.querySelector('[data-pool-add]').disabled"),'Offline pool unavailable');
  await evaluate("document.querySelector('[data-pool-add-alias]').value='Braum';document.querySelector('[data-pool-add]').click()");
  await waitFor(()=>evaluate("!!document.querySelector('[data-pool-remove=Braum]')"),'Offline pick not saved');
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(profile,'pick-pools.json'),'utf8')).utility.pair,['Braum']);
  await evaluate("document.querySelector('[data-pool-close]').click()");
  await evaluate("document.querySelector('[data-lab-preset=tanks]').click()");
  await waitFor(()=>evaluate("labView?.build?.alias === 'Jinx'"),'Preset did not change');
  assert.equal(await evaluate('labView.build.items.length'),6);
  assert.ok(await evaluate('labView.build.items.some(i=>i.id===3033)'));
  await evaluate("document.querySelector('[data-inspect-item]').click()");
  await waitFor(()=>evaluate("document.getElementById('inspect-item-dialog')?.open"),'Brak okna wyjaśnień');
  await evaluate(`(() => {const dlg=document.getElementById('inspect-item-dialog'), search=dlg.querySelector('input');
    search.value='IE'; search.dispatchEvent(new Event('input')); dlg.querySelector('form').requestSubmit();})()`);
  await waitFor(()=>evaluate("document.querySelector('[data-item-explanation] h3')?.textContent === 'Infinity Edge'"),'Skrót IE nie otworzył wyjaśnienia');
  await evaluate(`(() => {const dlg=document.getElementById('inspect-item-dialog'), search=dlg.querySelector('input');
    search.value='3036'; search.dispatchEvent(new Event('input')); dlg.querySelector('form').requestSubmit();})()`);
  await waitFor(()=>evaluate("document.querySelector('[data-item-explanation]').textContent.includes('Po dodaniu')"),'Brak symulacji dodania przedmiotu');
  await evaluate("document.querySelector('#inspect-item-dialog [data-close]').click()");
  await waitFor(()=>evaluate("document.querySelectorAll('#lab-results .icon-fallback').length > 0"),'Offline icon fallbacks missing');
  await evaluate("document.querySelector('.inventory-items [data-pin-item]').click()");
  await waitFor(()=>evaluate('labView.build.items[0].pinned'),'Offline pin did not apply');
  assert.equal(fs.readFileSync(path.join(profile,'choices.json'),'utf8'),'{}','Tester changed live preferences');
  assert.equal(await evaluate("document.querySelectorAll('#lab-results [data-runes],#lab-results [data-itemset],#lab-results [data-spells]').length"),0);
  await evaluate("document.getElementById('toast').hidden=true");
  await evaluate(`(async()=>{await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));await Promise.all(document.getAnimations().filter(a=>a.effect?.getTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));await new Promise(r=>requestAnimationFrame(r));})()`);
  fs.writeFileSync(path.resolve(profile,'../offline-lab.png'),(await win.webContents.capturePage()).toPNG());
  // Przejście do prawdziwego draftu zamyka tester, nawet jeśli jest otwarty.
  await evaluate("render({status:'champselect',myChampion:null,build:null,allies:[],enemies:[],suggestions:[],compositions:null,bans:[],enemyProfile:{count:0},mode:'classic'})");
  assert.equal(await evaluate('labActive'),false);
  console.log('PASS: offline catalog, six-item bot build, icon fallbacks, isolated pins, no live imports, live-draft return.');
  win.destroy();app.quit();
}).catch(e=>{console.error(e);app.exit(1);});
